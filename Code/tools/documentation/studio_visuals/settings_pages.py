def _screen(stem, identity, title, ui, tabs, active, subtitle):
    """! @brief 공통 설정 창과 적용 범위를 연결한다."""
    screen = Screen(stem, identity, title, ui=ui)
    dialog(screen, title, subtitle, tabs, active)
    return screen


def _stack(screen, x, y, width, height, title="기판 단면"):
    """! @brief 미정 두께를 임의 확정하지 않는 층 식별용 단면을 그린다."""
    screen.rect(x, y, width, height, PANEL, LINE, 3)
    screen.text(x + 18, y + 29, title, 17, INK, True, width - 36)
    layers = [
        ("상단 표면층", "미정", "#DAE7E0", 24),
        ("상단 동박", "미정", COPPER, 28),
        ("기판 유전체", "미정", BOARD, 90),
        ("하단 동박", "미정", COPPER, 28),
        ("하단 표면층", "미정", "#DAE7E0", 24),
    ]
    yy = y + 64
    for name, value, color, hh in layers:
        screen.rect(x + 20, yy, width - 40, hh, color, "#91A598")
        screen.text(x + 32, yy + hh / 2 + 5, name, 14, INK, width=width - 132)
        screen.text(x + width - 32, yy + hh / 2 + 5, value, 14, AMBER,
                    width=60, align="right")
        yy += hh + 6
    screen.text(x + 20, y + height - 38, "층 식별용 도식 / 두께 비례 아님", 13, MUTED, width=width - 40)
    screen.text(x + 20, y + height - 16, "실제 z 범위는 서비스 검토값 사용", 13, MUTED, width=width - 40)


