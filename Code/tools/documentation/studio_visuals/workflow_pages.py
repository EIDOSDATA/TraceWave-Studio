def footer(s, actions, hint, width=1344, height=820):
    """! @brief 화면 목적에 맞는 실제 동작과 초안 상태를 고정 위치에 둔다."""
    x = (1920 - width) / 2
    y = (1080 - height) / 2 + height - 74
    s.rect(x + 1, y + 1, width - 2, 72, WHITE, "none")
    s.line(x, y, x + width, y, LINE)
    total = sum(item[1] for item in actions) + 12 * (len(actions) - 1)
    s.text(x + 24, y + 45, hint, 13, MUTED, width=max(150, width - total - 72))
    xx = x + width - total - 24
    for action in actions:
        label, w, primary = action[:3]
        disabled = action[3] if len(action) > 3 else False
        s.button(xx, y + 20, w, label, primary, disabled=disabled)
        xx += w + 12


