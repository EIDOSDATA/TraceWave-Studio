def matching_curve(s, x, y, w, h):
    """! @brief 두 합성 곡선을 단위와 범례가 있는 비교 좌표에 표시한다."""
    s.rect(x, y, w, h, WHITE, LINE)
    left, top, pw, ph = x + 66, y + 60, w - 100, h - 112
    for i in range(5):
        yy = top + i * ph / 4
        s.line(left, yy, left + pw, yy, "#E6ECF4")
        s.text(left - 12, yy + 5, str(-i * 5), 13, MUTED, width=45, align="right")
    for i in range(5):
        xx = left + i * pw / 4
        s.line(xx, top, xx, top + ph, "#E6ECF4")
        s.text(xx, top + ph + 26, f"{2.40 + i * .02:.2f}", 13, MUTED, width=60, align="center")
    s.line(left, top + ph, left + pw, top + ph, MUTED)
    s.line(left, top, left, top + ph, MUTED)
    for shift, depth, color in [(0.40, 10, MUTED), (0.56, 16, BLUE)]:
        points = []
        for i in range(161):
            u = i / 160
            value = -2 - depth * math.exp(-((u - shift) / .21) ** 2)
            points.append((left + u * pw, top - value / 20 * ph))
        s.poly(points, "none", color, 2.5)
    s.text(x + 16, y + 28, "S11 [dB] / 합성 예시", 15, INK, True, w - 32)
    s.text(x + w - 18, y + h - 14, "주파수 [GHz]", 13, MUTED, width=150, align="right")
    s.line(x + w - 314, y + 25, x + w - 288, y + 25, MUTED, 2.5)
    s.text(x + w - 280, y + 30, "안테나 단독", 13, MUTED, width=110)
    s.line(x + w - 158, y + 25, x + w - 132, y + 25, BLUE, 2.5)
    s.text(x + w - 124, y + 30, "회로 결합", 13, BLUE, width=110)


